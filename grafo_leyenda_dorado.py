import networkx as nx
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

# 1. Crear el grafo no dirigido
G = nx.Graph()

nodos = {
    "A": ("Punto de encuentro de Guatavita", "Municipio"),
    "B": ("Museo Memorias del Dorado", "Museo"),
    "C": ("Mercado Sabores de la Tierra", "Mercado"),
    "D": ("Alojamiento El Mirador Dorado", "Alojamiento"),
    "E": ("Punto de encuentro de Sesquilé", "Municipio"),
    "F": ("Acceso a la Laguna del Cacique Guatavita", "Naturaleza"),
    "G": ("Parque Senderos del Agua", "Naturaleza"),
    "H": ("Alojamiento Refugio del Cacique", "Alojamiento")
}

for identificador, (nombre, categoria) in nodos.items():
    G.add_node(identificador, nombre=nombre, categoria=categoria)

# 2. Conexiones con distancia (km) y tiempo (min)
conexiones = [
    ("A", "B", 1, 5),
    ("A", "C", 2, 6),
    ("B", "C", 1, 4),
    ("B", "D", 4, 12),
    ("C", "D", 2, 8),
    ("A", "E", 16, 25),
    ("D", "E", 12, 22),
    ("D", "G", 9, 20),
    ("E", "G", 5, 12),
    ("E", "F", 12, 25),
    ("G", "F", 8, 18),
    ("G", "H", 3, 7),
    ("H", "F", 4, 10)
]

for origen, destino, distancia, tiempo in conexiones:
    G.add_edge(origen, destino, distancia=distancia, tiempo=tiempo)

# 3. Prueba: ruta de menor distancia entre A y F
ruta = nx.dijkstra_path(
    G, source="A", target="F", weight="distancia"
)

aristas_ruta = list(zip(ruta[:-1], ruta[1:]))

distancia_total = sum(G[u][v]["distancia"] for u, v in aristas_ruta)
tiempo_total = sum(G[u][v]["tiempo"] for u, v in aristas_ruta)

print("PRUEBA: RUTA DE MENOR DISTANCIA ENTRE A Y F")
print("Ruta:", " → ".join(ruta))
print(f"Distancia total: {distancia_total} km")
print(f"Tiempo de traslado: {tiempo_total} minutos")
print()

# 4. Posiciones para dibujar la red
posiciones = {
    "A": (0, 3),
    "B": (0, 1.5),
    "C": (2, 2.5),
    "D": (3, 1),
    "E": (4.5, 3.5),
    "F": (8.5, 3),
    "G": (6, 1.5),
    "H": (7, 0)
}

colores = {
    "Municipio": "#2563EB",
    "Museo": "#9333EA",
    "Mercado": "#EA580C",
    "Naturaleza": "#16A34A",
    "Alojamiento": "#795548"
}

bordes = [colores[G.nodes[nodo]["categoria"]] for nodo in G.nodes]

fig, ax = plt.subplots(figsize=(14, 8))

# Conexiones de la red
nx.draw_networkx_edges(
    G, posiciones, ax=ax,
    edge_color="gray",
    width=1.5
)

# Resaltar la ruta calculada
nx.draw_networkx_edges(
    G, posiciones, ax=ax,
    edgelist=aristas_ruta,
    edge_color="#DC2626",
    width=4
)

# Nodos circulares con borde por categoría
nx.draw_networkx_nodes(
    G, posiciones, ax=ax,
    node_color="white",
    edgecolors=bordes,
    node_size=1200,
    linewidths=2.5
)

nx.draw_networkx_labels(
    G, posiciones, ax=ax,
    font_size=16,
    font_weight="bold"
)

# Mostrar ambos pesos en cada conexión
etiquetas = {
    (u, v): f'{datos["distancia"]} km / {datos["tiempo"]} min'
    for u, v, datos in G.edges(data=True)
}

nx.draw_networkx_edge_labels(
    G, posiciones, ax=ax,
    edge_labels=etiquetas,
    font_size=9,
    rotate=False,
    bbox=dict(facecolor="white", edgecolor="none", alpha=0.9)
)

# 5. Leyenda
leyenda = [
    Line2D(
        [0], [0], marker="o", linestyle="",
        markerfacecolor="white",
        markeredgecolor=color,
        markeredgewidth=2,
        markersize=10,
        label=categoria
    )
    for categoria, color in colores.items()
]

leyenda.append(
    Line2D(
        [0], [0], color="#DC2626", linewidth=4,
        label="Ruta de menor distancia A → F"
    )
)

ax.legend(handles=leyenda, loc="upper left", frameon=False)

ax.set_title(
    'Red turística "La Leyenda del Dorado"\n'
    f'Ruta A → F: {distancia_total} km / {tiempo_total} min',
    fontsize=17
)

ax.margins(0.15)
ax.axis("off")

fig.text(
    0.5, 0.02,
    "Distancias y tiempos simulados · Representación no geográfica",
    ha="center", fontsize=10
)

plt.tight_layout(rect=(0, 0.05, 1, 1))
plt.show()

# Identificación de los destinos
for identificador, (nombre, _) in nodos.items():
    print(f"{identificador}: {nombre}")